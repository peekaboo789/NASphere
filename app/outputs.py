def _fmt_ts(value: Any) -> str:
    try:
        return time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(int(value)))
    except (TypeError, ValueError):
        return ""


def build_csv(rows: list[dict[str, Any]]) -> str:
    buf = io.StringIO()
    writer = csv.writer(buf, lineterminator="\r\n")
    writer.writerow(CSV_FIELDS)
    for r in rows:
        success = int(r.get("success_count") or 0)
        failure = int(r.get("failure_count") or 0)
        rate = round(success / max(1, success + failure) * 100, 1)
        speed = float(r.get("speed_kbps") or 0)
        writer.writerow(
            [
                r.get("name") or "",
                r.get("group_title") or "",
                r.get("tvg_id") or "",
                r.get("url") or "",
                r.get("source_url") or "",
                r.get("protocol") or "",
                r.get("ipv4_addr") or "",
                r.get("ipv6_addr") or "",
                r.get("family") or "",
                r.get("http_status") or "",
                r.get("final_url") or "",
                r.get("redirect_count") if r.get("redirect_count") is not None else "",
                r.get("content_type") or "",
                statuses.tri_label(r.get("hls_valid")),
                statuses.segment_label(r.get("segment_test")),
                "" if r.get("playable") is None else ("是" if r.get("playable") else "否"),
                round(float(r["connect_ms"]), 1) if r.get("connect_ms") else "",
                round(float(r["latency_ms"]), 1) if r.get("latency_ms") else "",
                round(float(r["elapsed_ms"]), 1) if r.get("elapsed_ms") else "",
                round(speed, 1),
                round(speed / 1024, 2),
                "有" if r.get("has_video") else "",
                "有" if r.get("has_audio") else "",
                r.get("v_codec") or "",
                r.get("a_codec") or "",
                r.get("v_resolution") or "",
                r.get("status") or "",
                statuses.label(r.get("status")),
                r.get("failure_reason") or "",
                success,
                failure,
                int(r.get("consecutive_failures") or 0),
                rate,
                _fmt_ts(r.get("first_seen")),
                _fmt_ts(r.get("last_seen")),
                _fmt_ts(r.get("last_tested_at")),
                _fmt_ts(r.get("last_ok_at")),
            ]
        )
    return buf.getvalue()


def _json_dict(raw: Any) -> dict[str, Any]:
    if isinstance(raw, dict):
        return dict(raw)
    try:
        value = json.loads(raw or "{}")
    except (TypeError, ValueError):
        return {}
    return value if isinstance(value, dict) else {}


def _json_list(raw: Any) -> list[Any]:
    if isinstance(raw, list):
        return list(raw)
    try:
        value = json.loads(raw or "[]")
    except (TypeError, ValueError):
        return []
    return value if isinstance(value, list) else []


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    with tmp.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    os.replace(tmp, path)


def write_outputs(rows_ok: list[dict[str, Any]], rows_all: list[dict[str, Any]], out_dir: Path) -> dict[str, int]:
    """写出全部产物，返回 {文件名: 频道数}。"""
    files: dict[str, int] = {}
    v4 = [r for r in rows_ok if r.get("family") == "ipv4"]
    v6 = [r for r in rows_ok if r.get("family") == "ipv6"]

    targets = {
        "iptv.m3u": build_m3u(rows_ok, "IPTV Auto Tester 可用频道"),
        "iptv_all.m3u": build_m3u(rows_all, "IPTV Auto Tester 全部频道"),
        "iptv_ipv4.m3u": build_m3u(v4, "IPTV Auto Tester IPv4"),
        "iptv_ipv6.m3u": build_m3u(v6, "IPTV Auto Tester IPv6"),
        "results.csv": "\ufeff" + build_csv(rows_all),
    }
    counts = {
        "iptv.m3u": len(rows_ok),
        "iptv_all.m3u": len(rows_all),
        "iptv_ipv4.m3u": len(v4),
        "iptv_ipv6.m3u": len(v6),
        "results.csv": len(rows_all),
    }
    for name, text in targets.items():
        _write(out_dir / name, text)
        files[name] = counts[name]
    return files
